#include "ft_printf.h"

int	print_string(char *s)
{
	int	i;
	int	counter;

	i = 0;
	counter = 0;
	if (s == NULL)
	{
		write(1, "(null)", 6);
		return (6);
	}
	while (s[i] != '\0')
	{
		counter += write(1, &s[i], 1);
		i++;
	}
	return (counter);
}
